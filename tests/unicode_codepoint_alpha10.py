def probe(tag, fn):
    try:
        print(tag, fn())
    except ValueError:
        print(tag, "<ValueError>")
    except IndexError:
        print(tag, "<IndexError>")
    except TypeError:
        print(tag, "<TypeError>")
    except KeyError:
        print(tag, "<KeyError>")


probe("U01", lambda: len("\u00e9"))
probe("U02", lambda: len("\u3042\u3044\u3046"))
probe("U03", lambda: "\u00e9"[0])
probe("U04", lambda: ord("\u00e9"))
